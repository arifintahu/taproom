"""Writes realm/avatar/layers.gno: the avatar art in a compact form for the Gno avatar package.

Each layer is a palette (6 hex digits per colour) and a list of runs, 4 characters per run from a
64-character alphabet: x, y, length - 1, colour index. Bodies, heads and caps share one pixel layout
across their variants, so they are stored once with a palette per base combo. Every encoded layer
is decoded again and compared with its source SVG before the file is written.

Usage: python export_gno.py <web/public/pixel> <realm/avatar/layers.gno>
"""
import os
import re
import sys

ALPHA = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_'
RUN = re.compile(r'M(\d+) (\d+)h(\d+)v1h-\d+z')
PATH = re.compile(r'<path fill="#([0-9a-fA-F]{6})" d="([^"]*)"')

# Base combos picked by the address hash: (skin index, beard, cap index). Matches the web app.
COMBOS = [(1, 'white', 0), (0, 'ginger', 1), (2, 'brown', 2), (3, 'black', 4),
          (4, 'grey', 3), (5, 'white', 5), (6, 'blond', 6), (7, 'grey', 7)]
SLOTS = [('hat', 'h', 100), ('outfit', 'o', 200), ('held', 'i', 300), ('companion', 'c', 400)]


def load(path):
    px = {}
    for col, d in PATH.findall(open(path, encoding='utf8').read()):
        for x, y, w in RUN.findall(d):
            for i in range(int(w)):
                px[(int(x) + i, int(y))] = col.lower()
    return px


def runs_of(px):
    """Horizontal runs of one colour, row by row: (x, y, length, colour)."""
    out = []
    for y in range(48):
        x = 0
        while x < 48:
            c = px.get((x, y))
            if c is None:
                x += 1
                continue
            x0 = x
            while x < 48 and px.get((x, y)) == c:
                x += 1
            out.append((x0, y, x - x0, c))
    return out


def encode(px, palette):
    idx = {c: i for i, c in enumerate(palette)}
    s = []
    for x, y, n, c in runs_of(px):
        assert n <= 64 and idx[c] < 64
        s.append(ALPHA[x] + ALPHA[y] + ALPHA[n - 1] + ALPHA[idx[c]])
    return ''.join(s)


def decode(palette, runs):
    px = {}
    for i in range(0, len(runs), 4):
        x, y, n, c = (ALPHA.index(ch) for ch in runs[i:i + 4])
        for k in range(n + 1):
            px[(x + k, y)] = palette[c]
    return px


def palette_of(px):
    """Colours in order of first appearance, scanning rows."""
    seen = []
    for _, _, _, c in runs_of(px):
        if c not in seen:
            seen.append(c)
    return seen


def template(files):
    """One shared run list for variants with the same layout; a palette per variant in slot order."""
    base = load(files[0])
    slots = palette_of(base)
    first = {c: next(p for p in sorted(base) if base[p] == c) for c in slots}
    runs = encode(base, slots)
    pals = []
    for f in files:
        v = load(f)
        assert set(v) == set(base), f + ': layout differs'
        pal = [v[first[c]] for c in slots]
        assert decode(pal, runs) == v, f + ': does not round-trip'
        pals.append(pal)
    return runs, pals


def go_str(s):
    return '"' + s + '"'


def main(pixel_dir, out_path):
    L = os.path.join(pixel_dir, 'layers')
    body_runs, body_pals = template([os.path.join(L, 'body', f'body_s{s}.svg') for s, _, _ in COMBOS])
    head_runs, head_pals = template([os.path.join(L, 'head', f'head_s{s}_{b}.svg') for s, b, _ in COMBOS])
    cap_runs, cap_pals = template([os.path.join(L, 'hat', f'cap_{c}.svg') for _, _, c in COMBOS])

    items = []
    for slot, prefix, base in SLOTS:
        for n in range(1, 13):
            f = os.path.join(L, slot, f'{prefix}{n}.svg')
            px = load(f)
            pal = palette_of(px)
            runs = encode(px, pal)
            assert decode(pal, runs) == px, f + ': does not round-trip'
            items.append((base + n, pal, runs))

    lines = [
        '// Code generated by tools/pixelart/export_gno.py from web/public/pixel/layers. DO NOT EDIT.',
        '',
        'package avatar',
        '',
        '// Shared layouts for the base gnome, with one palette per base combo (see Combo).',
        f'const bodyRuns = {go_str(body_runs)}',
        f'const headRuns = {go_str(head_runs)}',
        f'const capRuns = {go_str(cap_runs)}',
        '',
    ]
    for name, pals in (('bodyPal', body_pals), ('headPal', head_pals), ('capPal', cap_pals)):
        lines.append(f'var {name} = [8]string{{')
        lines += [f'\t{go_str("".join(p))},' for p in pals]
        lines += ['}', '']
    lines.append('// Items by realm item ID (slotBase + n): palette, then runs.')
    lines.append('var items = map[int][2]string{')
    lines += [f'\t{i}: {{{go_str("".join(p))}, {go_str(r)}}},' for i, p, r in items]
    lines += ['}', '']
    data = '\n'.join(lines)
    with open(out_path, 'w', encoding='utf8', newline='\n') as fh:
        fh.write(data)
    runs = sum(len(r) for _, _, r in items) // 4 + (len(body_runs) + len(head_runs) + len(cap_runs)) // 4
    print(f'wrote {out_path}: {len(data)} bytes, {runs} runs, 48 items, 8 base combos; all layers round-trip')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
